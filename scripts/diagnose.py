def scenario_audit() -> dict[str, Any]:
    """演示 ``record_prompt(prompt_id=...)`` 与 ``state["dry_run"]``。

    - ``prompt_id`` 会写入 ``rounds`` 与最终触发禁用的 ``disabled`` 记录，
      事后可在状态文件里重建"哪个入队 → 禁用哪个目录"的因果链；
    - ``dry_run=True`` 时决策会把审计字段写好，但不实际移动目录。
    """
    step = "4"
    env = _FakeComfyEnv(step_prefix=step)

    # ---- 4.2 注册模块并带 prompt_id 入队 ----
    env.make_module("audit_pkg")
    env.add_node("AuditNode", "audit_pkg")

    for i, pid in enumerate(["prompt-A", "prompt-B", "prompt-C"], start=1):
        auto_disable.record_prompt([], prompt_id=pid)
    snap = env.snapshot_state()
    # 从状态里重建因果链
    last_round = snap["rounds"][-1]
    audit_entry = snap["disabled"].get("audit_pkg", {})
    _emit(
        f"{step}.2",
        "3 次入队都带 prompt_id；audit_pkg 首次入队即被禁用（rounds<threshold 时 recent=rounds）",
        fields={
            "last_round_prompt_id": last_round.get("prompt_id"),
            "disabled_keys": list(snap["disabled"].keys()),
            "audit_pkg_disabled_at": audit_entry.get("disabled_at"),
            "audit_pkg_prompt_id": audit_entry.get("prompt_id"),
            "audit_pkg_status": audit_entry.get("status"),
        },
        result=(
            "OK"
            if audit_entry.get("prompt_id") == "prompt-A"
            and audit_entry.get("status") == "confirmed"
            else "FAIL: prompt_id/status 未正确写入"
        ),
    )

    # ---- 4.3 验证目录已被实际移动 ----
    _emit(
        f"{step}.3",
        "实际移动发生：custom_nodes/audit_pkg 已不在，.disabled/audit_pkg 在",
        fields={
            "custom_nodes_dir": env.list_custom_nodes(),
            "disabled_dir": env.disabled_targets(),
        },
        result="OK" if "audit_pkg" not in env.list_custom_nodes() else "FAIL",
    )

    # ---- 4.4 干跑模式：fresh 环境 + dry_run=True ----
    env.close()
    env = _FakeComfyEnv(step_prefix=step)
    env.make_module("dryrun_pkg")
    env.add_node("DryRunNode", "dryrun_pkg")

    # 改写状态文件里的 dry_run 标志
    with auto_disable._state_lock:
        s = auto_disable._load_state()
        s["dry_run"] = True
        auto_disable._save_state(s)
    for pid in ["dry-prompt-1", "dry-prompt-2", "dry-prompt-3"]:
        auto_disable.record_prompt([], prompt_id=pid)
    snap = env.snapshot_state()
    audit_entry = snap["disabled"].get("dryrun_pkg", {})
    _emit(
        f"{step}.4",
        "dry_run=True：决策产生 dry_run 审计条目但不移动目录",
        fields={
            "dry_run_flag": snap.get("dry_run"),
            "dryrun_pkg_status": audit_entry.get("status"),
            "dryrun_pkg_prompt_id": audit_entry.get("prompt_id"),
            "custom_nodes_dir_still_has": "dryrun_pkg" in env.list_custom_nodes(),
            "disabled_dir_has": "dryrun_pkg" in env.disabled_targets(),
        },
        result=(
            "OK"
            if audit_entry.get("status") == "dry_run"
            and "dryrun_pkg" in env.list_custom_nodes()
            and "dryrun_pkg" not in env.disabled_targets()
            else "FAIL"
        ),
    )

    summary = {
        "scenario": "audit",
        # dryrun_pkg 在第一次入队即触发禁用（与 audit_pkg 同样的原因），
        # 所以触发的 prompt_id 是 dry-prompt-1。
        "prompt_id_persisted": audit_entry.get("prompt_id") == "dry-prompt-1",
        "dry_run_honored": audit_entry.get("status") == "dry_run",
    }
    env.close()
    return summary


