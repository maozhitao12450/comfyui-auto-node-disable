def scenario_failure() -> dict[str, Any]:
    """模块在 NODE_CLASS_MAPPINGS 中，但物理目录已被人为删除。

    预期：``_decide`` 把它当作可禁用候选，``_disable_module`` 因路径
    缺失而 ``return False``；最终 ``state['disabled']`` 不会被写入。
    这正是真实环境中"误删目录后再触发起飞"的失败路径。
    """
    step = "3"
    env = _FakeComfyEnv(step_prefix=step)
    env.make_module("kept_pkg")
    env.make_module("ghost_pkg")
    env.add_node("KeptNode", "kept_pkg")
    env.add_node("GhostNode", "ghost_pkg")
    _emit(
        f"{step}.2",
        "注册 kept_pkg + ghost_pkg，再手动删除 ghost_pkg 的物理目录",
        fields={
            "before_delete": env.list_custom_nodes(),
        },
    )

    env.rm_module("ghost_pkg")
    _emit(
        f"{step}.3",
        "物理删除 ghost_pkg（模拟用户手动 rm -rf）",
        fields={
            "after_delete": env.list_custom_nodes(),
        },
        result="OK",
    )

    # 先让一次入队触发 scan：scan 仍能从 NODE_CLASS_MAPPINGS 里发现 ghost_pkg，
    # 但 _resolve_module_path 返回空串（路径不存在）。
    auto_disable.record_prompt([])  # 第 1 轮
    snap = env.snapshot_state()
    _emit(
        f"{step}.4",
        "首次入队（空 prompt）→ _scan_known_modules 仍能发现 ghost_pkg",
        fields={
            "known_modules": sorted(snap["known_modules"].keys()),
            "ghost_pkg_module_path": snap["known_modules"].get("ghost_pkg", {}).get(
                "module_path", ""
            ),
            "disabled_after": list(snap["disabled"].keys()),
        },
        result="ghost_pkg 出现在 known_modules 但 module_path 为空字符串",
    )

    # 继续触发到阈值
    auto_disable.record_prompt([])  # 第 2 轮
    auto_disable.record_prompt([])  # 第 3 轮：触发 _decide
    snap = env.snapshot_state()
    _emit(
        f"{step}.5",
        "第 3 轮入队：_decide 选中了 ghost_pkg 但 _disable_module 路径缺失失败",
        fields={
            "disabled_after": list(snap["disabled"].keys()),
            "ghost_pkg_in_disabled": "ghost_pkg" in snap["disabled"],
            "ghost_pkg_path_now": os.path.join(env.custom_nodes_dir, "ghost_pkg"),
            "still_exists_on_disk": os.path.exists(
                os.path.join(env.custom_nodes_dir, "ghost_pkg")
            ),
        },
        result=(
            "OK (disabled 中没有 ghost_pkg，因为 _disable_module 失败)"
            if "ghost_pkg" not in snap["disabled"]
            else "FAIL: 不应被记录为已禁用"
        ),
    )

    # ---- 3.6 排除名单：再注册一个模块并写入 exclude，验证不会被禁用 ----
    env.make_module("exempt_pkg")
    env.add_node("ExemptNode", "exempt_pkg")
    auto_disable.set_exclude(["exempt_pkg"])
    for _ in range(5):
        auto_disable.record_prompt([])
    snap = env.snapshot_state()
    _emit(
        f"{step}.6",
        "排除名单生效：exempt_pkg 命中 5 次也绝不被禁用",
        fields={
            "exclude": snap["exclude"],
            "disabled_after": list(snap["disabled"].keys()),
            "exempt_pkg_present": "exempt_pkg" in env.list_custom_nodes(),
        },
        result="OK" if "exempt_pkg" not in snap["disabled"] else "FAIL",
    )

    summary = {
        "scenario": "failure",
        "ghost_pkg_correctly_skipped": "ghost_pkg" not in snap["disabled"],
        "exempt_pkg_respected": "exempt_pkg" not in snap["disabled"],
    }
    env.close()
    return summary


