def main(argv: Iterable[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="脱离 ComfyUI 宿主演练 auto_disable 的核心路径。"
    )
    parser.add_argument(
        "--scenario",
        choices=list(SCENARIOS) + ["all"],
        default="all",
        help="选择要跑的单个场景，默认 all。",
    )
    args = parser.parse_args(argv)

    _print_header()

    selected = (
        list(SCENARIOS) if args.scenario == "all" else [args.scenario]
    )
    results: list[dict[str, Any]] = []
    for name in selected:
        print("-" * 72)
        print(f"### 场景：{name}")
        print("-" * 72)
        try:
            results.append(SCENARIOS[name]())
        except Exception as e:  # 捕获并诊断，不要让脚本崩
            print(f"[STEP ?] 场景 {name} 抛出未处理异常: {e!r}")
            results.append({"scenario": name, "error": repr(e)})

    print("=" * 72)
    print("汇总")
    print("=" * 72)
    for r in results:
        print(json.dumps(r, ensure_ascii=False, indent=2))
    return 0


