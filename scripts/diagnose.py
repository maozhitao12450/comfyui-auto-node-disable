def scenario_restore() -> dict[str, Any]:
    step = "2"
    env = _FakeComfyEnv(step_prefix=step)
    env.make_module("revive_pkg")
    env.add_node("ReviveNode", "revive_pkg")

    # ---- 2.2 触发禁用 ----
    for _ in range(3):
        auto_disable.record_prompt([])  # 完全空 prompt：所有已知模块都会被禁用
    snap = env.snapshot_state()
    _emit(
        f"{step}.2",
        "空入队 3 次以触发禁用",
        fields={
            "disabled_after": list(snap["disabled"].keys()),
            "custom_nodes_dir": env.list_custom_nodes(),
            "disabled_dir": env.disabled_targets(),
        },
        result="OK" if "revive_pkg" in env.disabled_targets() else "FAIL",
    )

    # ---- 2.3 调用 restore_module ----
    ok = auto_disable.restore_module("revive_pkg")
    snap = env.snapshot_state()
    _emit(
        f"{step}.3",
        "调用 restore_module('revive_pkg')",
        fields={
            "restore_returned": ok,
            "disabled_after": list(snap["disabled"].keys()),
            "custom_nodes_dir": env.list_custom_nodes(),
            "disabled_dir": env.disabled_targets(),
        },
        result="OK" if ok and "revive_pkg" not in snap["disabled"] else "FAIL",
    )

    summary = {
        "scenario": "restore",
        "restore_ok": ok,
        "revive_pkg_present_after_restore": "revive_pkg" in env.list_custom_nodes(),
    }
    env.close()
    return summary


