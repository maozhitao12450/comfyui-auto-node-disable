"""scripts/diagnose.py
============================
ComfyUI Auto Node Disable —— 独立可运行的复现 / 诊断入口。

目的
----
在没有 ComfyUI 宿主的情况下演练本插件的核心路径，并输出可关联到
``auto_disable.py`` 中具体决策步骤的结构化诊断信息，便于：

* 在没有 ComfyUI 服务的环境中回归核心逻辑；
* 在真实生产环境出现"为什么 X 模块被禁用 / 没被禁用"等问题时，
  把脚本当作诊断器逐步还原现场。

设计
----
脚本本身不修改 ``auto_disable`` 的产品行为，只在以下两点上接入：

1. 通过 ``sys.modules['nodes']`` 注入一个伪造的 ``nodes`` 模块，
   让 ``auto_disable._custom_nodes_dir()`` 与 ``_scan_known_modules()``
   能够找到 ``custom_nodes`` 根目录与全局节点映射；
2. 在临时目录里按真实结构摆好 ``custom_nodes/<name>/`` 与
   ``custom_nodes/.disabled/``，使 ``_disable_module`` 与
   ``restore_module`` 的副作用落在隔离的临时树里。

输出
----
每个关键动作都用 ``[STEP X.Y]`` 标号 + 关键字段 + 结论的形式打印。
运行本脚本后即可根据 STEP 编号在 ``auto_disable.py`` 中定位到对应的
函数 / 分支（例如 ``[STEP 3.4]`` 对应 ``_decide`` 中的
"if node_classes.isdisjoint(used_union)" 分支）。

运行方式
--------
::

    python scripts/diagnose.py
    python scripts/diagnose.py --scenario failure      # 只跑失败场景
    python scripts/diagnose.py --scenario restore      # 只跑恢复场景
    python scripts/diagnose.py --scenario normal       # 只跑正常场景

依赖
----
仅 Python 标准库。脚本退出时会清理临时目录与 ``sys.modules['nodes']``。
"""

