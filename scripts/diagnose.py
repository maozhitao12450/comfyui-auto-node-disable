def scenario_normal() -> dict[str, Any]:
    """三次入队都用不到 ``unused_pkg``，预期它会被自动移动到 ``.disabled``。"""
    step = "1"
    env = _FakeComfyEnv(step_prefix=step)

    # ---- 1.2 安装两个模块 ----
    env.make_module("kept_pkg")        # 始终被使用
    env.make_module("unused_pkg")      # 始终不被使用
    env.add_node("KeptNode", "kept_pkg")
    env.add_node("UnusedNode", "unused_pkg")
    _emit(
        f"{step}.2",
        "注册两个 custom_node 模块（kept_pkg / unused_pkg）",
        fields={
            "known_modules(before scan)": {},
            "custom_nodes_dir_listing": env.list_custom_nodes(),
        },
        result="OK",
    )

    # ---- 1.3 模拟首次入队（带 ON_PROMPT 钩子提取节点类的同样路径）----
    used = auto_disable.extract_used_class_names(
        {"prompt": {"1": {"class_type": "KeptNode", "inputs": {}}}}
    )
    auto_disable.record_prompt(used)
    # 注意：auto_disable._decide 在 rounds 不足 threshold 时取 "全部 rounds" 作为
    # recent，所以单次入队也可能触发禁用；脚本注释如实反映这一行为。
    snap = env.snapshot_state()
    _emit(
        f"{step}.3",
        "第 1 次入队（仅使用 KeptNode）；rounds<threshold 时 _decide 用全部 rounds",
        fields={
            "used_classes": used,
            "rounds_len": len(snap["rounds"]),
            "disabled_after": list(snap["disabled"].keys()),
            "known_modules": sorted(snap["known_modules"].keys()),
        },
        result=(
            "disabled_count>=1 (rounds<threshold 时 recent=rounds)"
            if snap["disabled"] else "disabled_count=0"
        ),
    )

    # ---- 1.4 第 2 次入队 ----
    auto_disable.record_prompt(used)
    snap = env.snapshot_state()
    _emit(
        f"{step}.4",
        "第 2 次入队（仍然只用 KeptNode）",
        fields={
            "rounds_len": len(snap["rounds"]),
            "disabled_after": list(snap["disabled"].keys()),
        },
        result=(
            f"disabled_count={len(snap['disabled'])} (累计)"
        ),
    )

    # ---- 1.5 第 N 次入队：触发 _decide 命中 ----
    before_listing = env.list_custom_nodes()
    auto_disable.record_prompt(used)
    snap = env.snapshot_state()
    after_listing = env.list_custom_nodes()
    _emit(
        f"{step}.5",
        "第 3 次入队：_decide 命中阈值，unused_pkg 应被移动",
        fields={
            "rounds_len": len(snap["rounds"]),
            "used_union_recent": sorted(
                set().union(*(r["used_classes"] for r in snap["rounds"][-3:]))
            ),
            "disabled_after": list(snap["disabled"].keys()),
            "custom_nodes_dir_before": before_listing,
            "custom_nodes_dir_after": after_listing,
            "disabled_dir_listing": env.disabled_targets(),
        },
        result=(
            "OK" if "unused_pkg" in env.disabled_targets() else "FAIL: 未触发移动"
        ),
    )

    # ---- 1.6 二次 _decide 不应重复禁用 ----
    auto_disable.record_prompt(used)
    snap = env.snapshot_state()
    _emit(
        f"{step}.6",
        "继续入队：已被禁用的模块应被 _decide 跳过",
        fields={
            "disabled_after": list(snap["disabled"].keys()),
            "disabled_dir_listing": env.disabled_targets(),
        },
        result="OK (disabled 计数保持 1)",
    )

    summary = {
        "scenario": "normal",
        "final_disabled": list(snap["disabled"].keys()),
        "disabled_dir": env.disabled_targets(),
        "kept_pkg_present": "kept_pkg" in env.list_custom_nodes(),
    }
    env.close()
    return summary


